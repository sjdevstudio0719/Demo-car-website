export function formatPrice(value) {
  const lakh = value / 100000
  return `₹${lakh % 1 === 0 ? lakh.toFixed(0) : lakh.toFixed(2)} Lakh`
}

export function formatKm(value) {
  return `${value.toLocaleString('en-IN')} km`
}
